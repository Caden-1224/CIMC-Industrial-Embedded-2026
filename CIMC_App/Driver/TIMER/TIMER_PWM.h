#ifndef __TIMER_PWM_H__
#define __TIMER_PWM_H__

/************************* 头文件 *************************/

#include "HeaderFiles.h"

/************************* 宏定义 *************************/

/* PWM 自动重装载值，实际计数周期为 (TIMER_PWM_ARR + 1) 个计数节拍。 */
#define TIMER_PWM_ARR              (10000U - 1U)

/* 占空比输入的业务上限，单位为百分比。 */
#define TIMER_PWM_MAX_DUTY_PERCENT 100U

/************************ 函数定义 ************************/

/**
 * @brief  初始化 PWM 输出模块。
 * @details 该接口会完成两部分硬件配置：
 *          1. 将 `PC6` 配置为 `TIMER2_CH0` 的复用功能输出；
 *          2. 将 `TIMER2` 配置为 `PWM 模式 1`，并将默认占空比初始化为 `0%`。
 *
 *          当前实现专门服务于独立 PWM 测试：
 *          - 输出引脚固定为 `PC6`
 *          - 该脚当前未被本工程其他模块占用
 *          - 使用时请把外部小灯或测试线接到 `PC6`
 *
 * @param  void 无输入参数。
 * @return void 无返回值。
 */
void my_timer_init(void);

/**
 * @brief  设置 PWM 占空比。
 * @details 业务层只需要传入百分比，本接口会自动完成占空比到比较寄存器的换算：
 *          - `0` 表示整周期保持低电平；
 *          - `100` 表示接近满占空比输出；
 *          - 大于 `100` 的输入会在驱动层被钳制到 `100`。
 *
 *          该函数只更新当前 PWM 通道的比较值，不会重复初始化 GPIO 或定时器。
 *
 * @param  duty 目标占空比，单位为百分比，推荐范围 `0~100`。
 * @return void 无返回值。
 */
void my_timer_set_duty(uint8_t duty);

#endif
